// Current language (KK default, saved in localStorage)
let currentLang = localStorage.getItem("kazmorph_lang") || "kk";

/** Get translated string by key */
function t(key) {
    return (I18N[currentLang] && I18N[currentLang][key]) || I18N.kk[key] || key;
}

/** Apply current language to all DOM elements */
function applyLang() {
    document.documentElement.lang = currentLang;
    document.title = t("page_title");

    document.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = t(el.getAttribute("data-i18n"));
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });

    document.querySelectorAll(".lang-btn").forEach(btn => {
        btn.classList.toggle("active", btn.dataset.lang === currentLang);
    });

    // Re-render analysis results on language switch, but only on pages that
    // define these functions (dashboard/app/query_detail). Auth pages skip.
    if (lastResult && typeof renderStats === "function" && typeof renderTable === "function") {
        renderStats(lastResult);
        renderTable(lastResult);
    }

    if (typeof updateCharCount === "function") updateCharCount();
}

/** Switch language and persist */
function setLang(lang) {
    currentLang = lang;
    localStorage.setItem("kazmorph_lang", lang);
    applyLang();
}

/* Auto-apply the current language on load. Page-specific scripts (app.js,
   dashboard.js, query_detail.js) also call applyLang() — that's fine, it's
   idempotent. This guarantees pages that load only i18n.js (e.g. /dashboard)
   still get their [data-i18n] elements filled instead of empty borders. */
function _i18n_autoApply() {
    // Wire language switcher buttons if present.
    document.querySelectorAll(".lang-btn").forEach(btn => {
        if (!btn._i18n_bound) {
            btn.addEventListener("click", () => setLang(btn.dataset.lang));
            btn._i18n_bound = true;
        }
    });
    applyLang();
}
if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", _i18n_autoApply);
} else {
    _i18n_autoApply();
}
